/* RENDER PLANETS */

function renderPlanets(list = planets) {

    planetGrid.innerHTML = "";

    if (list.length === 0) {

        planetGrid.innerHTML = `
            <div style="
                grid-column:1/-1;
                text-align:center;
                padding:50px;
                color:#9da8c7;
            ">
                <h3>No planets found 🌌</h3>
                <p>Try another search.</p>
            </div>
        `;

        return;
    }

    list.forEach((planet, index) => {

        const card = document.createElement("article");

        card.className = "planet-card";

        card.innerHTML = `

            <div class="planet-visual">

                <div class="planet-ball ${planet.color}"></div>

            </div>

            <h3>${planet.name}</h3>

            <p class="planet-type">
                ${planet.order} • ${planet.type}
            </p>

            <div class="planet-mini">

                <span class="mini-stat">
                    🌙 ${planet.moons} moons
                </span>

                <span class="mini-stat">
                    📏 ${planet.diameter}
                </span>

            </div>

            <button
                class="details-btn"
                data-index="${index}"
            >
                Explore Planet →
            </button>

        `;

        planetGrid.appendChild(card);
    });


    document.querySelectorAll(".details-btn").forEach(button => {

        button.addEventListener("click", () => {

            const index = Number(button.dataset.index);

            openPlanet(planets[index]);

        });

    });
}


